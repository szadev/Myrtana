using System;
using System.Collections.Generic;
using System.Globalization;
using System.Linq;
using System.Text;

namespace Myrtana.Ui.Skin
{
    /// <summary>
    /// Writes the generated G3 theme style sheet (<c>G3Theme.uss</c>) from the theme data: one class per widget part with
    /// its image, 9-slice, tint and text colour per state, plus rules that dress UI Toolkit's built-in scroll bars,
    /// sliders and toggles inside <c>.g3-root</c> with the theme images.
    /// <para>
    /// A <b>part</b> is a theme element pair <c>X_back</c>/<c>X_front</c> (or a single element). The host element gets
    /// class <c>g3-X</c> and draws the back layer as its background; an optional child with class <c>g3-front</c> draws
    /// the front layer. States: <c>:focus</c>/<c>.g3--focus</c> = Focus, <c>:hover</c>/<c>.g3--hover</c> = MouseOver,
    /// <c>:active</c>/<c>:checked</c>/<c>.g3--selected</c> = Pressed, <c>:disabled</c>/<c>.g3--disabled</c> = Disabled.
    /// Rules are emitted in <see cref="WidgetStates.CascadeOrder"/>, so the later (stronger) state wins like
    /// <see cref="WidgetStates.Resolve"/>. Text colour is inherited by labels inside the host.
    /// </para>
    /// </summary>
    public static class ThemeUssWriter
    {
        public const string FrontClass = "g3-front";
        public const string SelectedClass = "g3--selected";
        public const string FocusClass = "g3--focus";
        public const string DisabledClass = "g3--disabled";
        /// <summary>Forces the MouseOver look without a pointer (screenshots, tests, gamepad "hot" item).</summary>
        public const string HoverClass = "g3--hover";
        public const string RootClass = "g3-root";

        /// <summary>Back layers of list rows: a soft single-colour bar whose per-state blend is the highlight colour.</summary>
        static readonly HashSet<string> RowHighlights = new HashSet<string>(StringComparer.OrdinalIgnoreCase)
        {
            "listctrl_item_details_back", "listctrl_item_list_back", "listbox_item_back", "combobox_list_item_back",
        };

        /// <summary>
        /// True for theme elements imported as a white alpha mask, so the state tints show as G3 names them (focus
        /// #FF8080, hover #FFC0C0, selected #FF0000). The bar's own brown would multiply them into nearly one colour, and
        /// the front layer (white blend in every visible state) draws the brown glow on top anyway. [inferred]
        /// </summary>
        public static bool IsTintMask(string element) => RowHighlights.Contains(element);

        /// <summary>USS class of a part: "listctrl_item_tiles" → "g3-listctrl-item-tiles".</summary>
        public static string PartClass(string part) => "g3-" + part.Replace('_', '-');

        /// <summary>Part name of an element: strips "_back"/"_front".</summary>
        public static string PartOf(string element)
        {
            if (element.EndsWith("_back", StringComparison.Ordinal)) return element.Substring(0, element.Length - 5);
            if (element.EndsWith("_front", StringComparison.Ordinal)) return element.Substring(0, element.Length - 6);
            return element;
        }

        /// <param name="imageUrl">Maps an element image key to a USS url (e.g. "/Assets/G3Imported/Gui/Theme/x.png").</param>
        public static string Write(ThemeData theme, Func<string, string> imageUrl)
        {
            var sb = new StringBuilder();
            sb.AppendLine("/* GENERATED by G3/GUI/Import from gui.pak theme_g3.thm — do not edit; see Docs/ui-skin.md. */");
            sb.AppendLine();
            int border = theme.Metric("Border.Control.X", 3);

            var parts = new List<(string part, ThemeElementData back, ThemeElementData front)>();
            var byName = theme.Elements.ToDictionary(e => e.Name, StringComparer.OrdinalIgnoreCase);
            foreach (var e in theme.Elements)
            {
                if (e.Name.EndsWith("_front", StringComparison.Ordinal) && byName.ContainsKey(PartOf(e.Name) + "_back")) continue;
                string part = PartOf(e.Name);
                byName.TryGetValue(part + "_front", out var front);
                if (!e.Name.EndsWith("_back", StringComparison.Ordinal)) front = null;
                parts.Add((part, e, front));
            }

            foreach (var (part, back, front) in parts)
            {
                string cls = "." + PartClass(part);
                Rule(sb, cls, Image(back, imageUrl, border), Colors(back, WidgetState.Normal, true));
                if (front != null)
                    Rule(sb, cls + " > ." + FrontClass, FrontBase(front, imageUrl, border), Colors(front, WidgetState.Normal, false));
                foreach (var state in WidgetStates.CascadeOrder.Skip(1))
                {
                    string sel = string.Join(", ", StateSelectors(state).Select(s => cls + s));
                    Rule(sb, sel, Colors(back, state, true));
                    if (front != null)
                        Rule(sb, string.Join(", ", StateSelectors(state).Select(s => cls + s + " > ." + FrontClass)), Colors(front, state, false));
                }
                sb.AppendLine();
            }

            WriteBuiltIns(sb, theme, byName, imageUrl);
            return sb.ToString();
        }

        static IEnumerable<string> StateSelectors(WidgetState s)
        {
            switch (s)
            {
                case WidgetState.Focus: return new[] { ":focus", "." + FocusClass };
                case WidgetState.MouseOver: return new[] { ":hover", "." + HoverClass };
                case WidgetState.Pressed: return new[] { ":active", ":checked", "." + SelectedClass };
                case WidgetState.Disabled: return new[] { ":disabled", "." + DisabledClass };
                default: return new[] { "" };
            }
        }

        static IEnumerable<string> Image(ThemeElementData e, Func<string, string> url, int border)
        {
            yield return $"background-image: url(\"{url(e.Image)}\")";
            yield return "-unity-background-scale-mode: stretch-to-fill";
            if (e.Slice != null && e.Slice.Length == 4)
            {
                yield return $"-unity-slice-left: {e.Slice[0]}";
                yield return $"-unity-slice-top: {e.Slice[1]}";
                yield return $"-unity-slice-right: {e.Slice[2]}";
                yield return $"-unity-slice-bottom: {e.Slice[3]}";
                int max = Math.Max(1, e.Slice.Max());
                yield return "-unity-slice-scale: " + F((float)border / max) + "px";
            }
        }

        static IEnumerable<string> FrontBase(ThemeElementData e, Func<string, string> url, int border)
        {
            yield return "position: absolute";
            yield return "left: 0; top: 0; right: 0; bottom: 0";
            yield return "background-color: rgba(0, 0, 0, 0)";
            foreach (var p in Image(e, url, border)) yield return p;
        }

        static IEnumerable<string> Colors(ThemeElementData e, WidgetState s, bool withText)
        {
            yield return "-unity-background-image-tint-color: " + Uss(e.Blend(s));
            if (withText) yield return "color: " + Uss(e.Text(s));
        }

        static void Rule(StringBuilder sb, string selector, params IEnumerable<string>[] blocks)
        {
            sb.Append(selector).AppendLine(" {");
            foreach (var b in blocks)
                foreach (var p in b) sb.Append("    ").Append(p).AppendLine(";");
            sb.AppendLine("}");
        }

        /// <summary>Scroll bars, sliders and toggles of UI Toolkit inside a <c>.g3-root</c> panel.</summary>
        static void WriteBuiltIns(StringBuilder sb, ThemeData theme, Dictionary<string, ThemeElementData> el, Func<string, string> url)
        {
            int track = theme.Metric("VScroll.Track.X", 17);
            string root = "." + RootClass + " ";
            string Img(string name) => el.TryGetValue(name, out var e) ? $"url(\"{url(e.Image)}\")" : "none";
            string Tint(string name, WidgetState s) => el.TryGetValue(name, out var e) ? Uss(e.Blend(s)) : "rgb(255, 255, 255)";
            var plain = new[] { "background-color: rgba(0, 0, 0, 0)", "border-width: 0", "-unity-background-scale-mode: stretch-to-fill" };

            sb.AppendLine("/* ---- UI Toolkit built-in controls inside .g3-root ---- */");
            foreach (var (axis, dir, size, low, high) in new[]
                     { ("vertical", "ver", "width", "arrow_up", "arrow_down"), ("horizontal", "hor", "height", "arrow_left", "arrow_right") })
            {
                string sc = root + ".unity-scroller--" + axis;
                Rule(sb, sc, new[] { $"{size}: {track}px", $"min-{size}: {track}px", "background-color: rgba(0, 0, 0, 0)", "border-width: 0" });
                Rule(sb, sc + " .unity-base-slider__tracker", plain, new[]
                    { $"background-image: {Img($"scrollbar_{dir}_track_back")}", $"-unity-background-image-tint-color: {Tint($"scrollbar_{dir}_track_back", WidgetState.Normal)}" });
                Rule(sb, sc + " .unity-base-slider__dragger", plain, new[]
                    { $"background-image: {Img($"scrollbar_{dir}_thumb_back")}", $"-unity-background-image-tint-color: {Tint($"scrollbar_{dir}_thumb_back", WidgetState.Normal)}" });
                Rule(sb, sc + " .unity-base-slider__dragger-border", new[] { "border-width: 0", "background-color: rgba(0, 0, 0, 0)" });
                Rule(sb, sc + " .unity-scroller__low-button", plain, new[] { $"background-image: {Img($"scrollbar_{dir}_{low}_front")}", $"{size}: {track}px" });
                Rule(sb, sc + " .unity-scroller__high-button", plain, new[] { $"background-image: {Img($"scrollbar_{dir}_{high}_front")}", $"{size}: {track}px" });
                Rule(sb, sc + " .unity-scroller__low-button:hover, " + sc + " .unity-scroller__high-button:hover", new[] { "-unity-background-image-tint-color: " + Uss(G3Palette.TextHighlight) });
            }

            Rule(sb, root + ".unity-slider .unity-base-slider__tracker", plain, new[]
                { $"background-image: {Img("trackbar_hor_track_back")}", $"-unity-background-image-tint-color: {Tint("trackbar_hor_track_back", WidgetState.Normal)}" });
            Rule(sb, root + ".unity-slider .unity-base-slider__dragger", plain, new[]
                { $"background-image: {Img("trackbar_hor_thumb_back")}", $"-unity-background-image-tint-color: {Tint("trackbar_hor_thumb_back", WidgetState.Normal)}" });
            Rule(sb, root + ".unity-slider .unity-base-slider__dragger:hover", new[]
                { $"-unity-background-image-tint-color: {Tint("trackbar_hor_thumb_back", WidgetState.MouseOver)}" });
            Rule(sb, root + ".unity-toggle .unity-toggle__checkmark", plain, new[]
                { $"background-image: {Img("button_checkbox_front")}", $"width: {theme.Metric("CheckBox.Box.X", 17)}px", $"height: {theme.Metric("CheckBox.Box.Y", 17)}px" });
            Rule(sb, root + ".unity-toggle:checked .unity-toggle__checkmark", new[] { $"background-image: {Img("button_check_back")}" });
        }

        /// <summary>USS colour literal: rgba(r, g, b, a) with alpha 0…1.</summary>
        public static string Uss(SkinColor c) => $"rgba({c.R}, {c.G}, {c.B}, {F(c.A / 255f)})";

        static string F(float v) => v.ToString("0.###", CultureInfo.InvariantCulture);
    }
}
