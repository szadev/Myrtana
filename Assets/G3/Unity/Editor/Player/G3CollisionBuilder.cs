    /// <summary>
    /// Adds colliders to imported Gothic 3 objects under a root (usually the "G3World" GameObject or one streamed cell).
    /// Idempotent: objects that already carry a collider (or a "G3Collision" child) are left alone.
    ///
    /// Per static mesh object, matched back to its world entity by position + name:
    /// 1. entity has eCCollisionShape_PS with shapes → those shapes (TriMesh/ConvexHull from the .xnvmsh, Box, Sphere,
    ///    Capsule); only player-relevant groups (Undefined, Static, Dynamic, Tree_Trunk, Door) and non-trigger shapes.
    /// 2. entity has eCCollisionShape_PS without shapes (lazily generated by the engine) → "&lt;mesh&gt;.xnvmsh",
    ///    or the render mesh when the game would re-cook it (missing or obsolete .xnvmsh).
    /// 3. entity has no collision property set → no collider (the game has none either).
    /// 4. no entity found → heuristic: terrain / large meshes get a render-mesh MeshCollider, small solid ones a box;
    ///    alpha-clipped foliage, water and decals are skipped.
    /// Trees (SpeedTree replacement prefabs under ".../Trees") get a trunk capsule.
    /// Collision meshes are cached as assets in Assets/G3Imported/Collision (×0.01, same axes as render meshes). Triangle
    /// meshes are built two-sided (<see cref="CollisionRules.TwoSided"/>): G3's collision blocks from both sides, but the
    /// cooked winding is inconsistent (whole hut/house sub-meshes face inwards), and a one-sided MeshCollider lets the
    /// CharacterController through back faces. Render-mesh fallback colliders get a two-sided copy as well (not terrain).
    /// </summary>
    public static class G3CollisionBuilder
    {
        public const string CollisionRoot = G3AssetCache.Root + "/Collision";
        const string ChildName = "G3Collision";
        const float S = G3AssetCache.Scale;

        public sealed class Stats
        {
            public int Objects, Skipped, AlreadyDone, FromXnvmsh, FromLazyXnvmsh, FromRender, Primitives, Trees, NoCollisionInGame,
                Unmatched, MeshAssetsCreated, Colliders;
            public override string ToString() =>
                $"objects {Objects}: xnvmsh shapes {FromXnvmsh}, lazy xnvmsh {FromLazyXnvmsh}, render-mesh {FromRender}, " +
                $"primitive-only {Primitives}, trees {Trees}, no collision in G3 {NoCollisionInGame}, skipped {Skipped}, " +
                $"already done {AlreadyDone}, unmatched entities {Unmatched}; {Colliders} colliders, {MeshAssetsCreated} new mesh assets";
        }

        // ------------------------------------------------------------------ caches (per editor domain)

        sealed class EntityRec
        {
            public string Name, Resource;
            public float[] World;
            public List<CollisionShape> Shapes;
            public bool IsWater;
        }

        static Dictionary<(int, int, int), List<EntityRec>> _entities;
        static G3FileSystem _fs;
        static readonly Dictionary<string, CollisionMeshResource> _xnv = new Dictionary<string, CollisionMeshResource>(StringComparer.OrdinalIgnoreCase);
        static readonly Dictionary<string, Mesh> _meshes = new Dictionary<string, Mesh>(StringComparer.OrdinalIgnoreCase);

        [InitializeOnLoadMethod]
        static void HookReload() => AssemblyReloadEvents.beforeAssemblyReload += ClearCaches;

        /// <summary>Drops the entity index, open paks and mesh caches.</summary>
        public static void ClearCaches()
        {
            _fs?.Dispose();
            _fs = null;
            _entities = null;
            _xnv.Clear();
            _meshes.Clear();
            _surfaces.Clear();
        }

        static G3FileSystem Fs => _fs ??= new G3FileSystem(G3WorldImporter.DataDir, "_compiledPhysic", "_compiledMesh");

        /// <summary>Index of every world entity with a visual, keyed by its origin in whole centimetres.</summary>
        static Dictionary<(int, int, int), List<EntityRec>> Entities
        {
            get
            {
                if (_entities != null) return _entities;
                var dict = new Dictionary<(int, int, int), List<EntityRec>>();
                using (var projects = new G3FileSystem(G3WorldImporter.DataDir, "Projects_compiled"))
                {
                    const string vol = "Projects_compiled/";
                    // Story-switchable sectors that are off at the start are placed by G3WorldImporter too (under their
                    // G3SectorContent holder): their objects get the game's collision as well (polish-3).
                    var layout = WorldLayout.Build(projects.Files.Select(f => f.Path), p => projects.Get(vol + p)?.Read(), includeDisabled: true);
                    var story = G3StorySectorList.Load(layout);
                    layout.Sectors.RemoveAll(s => !s.Enabled && !story.ContainsKey(s.Name));
                    foreach (var sector in layout.Sectors)
                    foreach (var node in sector.Nodes.Concat(sector.Lrentdats)) // .lrentdat: beds, benches … (DynamicObjects)
                    {
                        List<WorldEntity> list;
                        try
                        {
                            var entry = projects.Get(vol + node);
                            list = entry != null ? EntityArchive.Read(entry.Read(), decodeVegetation: false) : null;
                        }
                        catch (Exception) { continue; }
                        if (list == null) continue;
                        foreach (var e in list)
                        {
                            if (e.Visual == VisualKind.None) continue;
                            var key = Key(e.World[12], e.World[13], e.World[14]);
                            if (!dict.TryGetValue(key, out var l)) dict[key] = l = new List<EntityRec>(1);
                            l.Add(new EntityRec { Name = e.Name, Resource = e.Resource, World = e.World, Shapes = e.CollisionShapes, IsWater = e.IsWater });
                        }
                    }
                }
                return _entities = dict;
            }
        }

        static (int, int, int) Key(float x, float y, float z) => (Mathf.RoundToInt(x), Mathf.RoundToInt(y), Mathf.RoundToInt(z));

        static EntityRec FindEntity(Vector3 posCm, string goName, string meshName)
        {
            var k = Key(posCm.x, posCm.y, posCm.z);
            EntityRec best = null;
            int bestScore = -1;
            for (int dx = -1; dx <= 1; dx++)
            for (int dy = -1; dy <= 1; dy++)
            for (int dz = -1; dz <= 1; dz++)
            {
                if (!Entities.TryGetValue((k.Item1 + dx, k.Item2 + dy, k.Item3 + dz), out var list)) continue;
                foreach (var r in list)
                {
                    int score = 0;
                    if (!string.IsNullOrEmpty(r.Name) && r.Name == goName) score += 2;
                    if (meshName != null && Stem(r.Resource).Equals(meshName, StringComparison.OrdinalIgnoreCase)) score += 1;
                    if (meshName != null && Stem(r.Resource).Equals(goName, StringComparison.OrdinalIgnoreCase)) score += 1;
                    if (dx == 0 && dy == 0 && dz == 0) score += 1;
                    if (score > bestScore) { bestScore = score; best = r; }
                }
            }
            return best;
        }

        static string Stem(string file) => string.IsNullOrEmpty(file) ? "" : Path.GetFileNameWithoutExtension(file);

        static CollisionMeshResource LoadXnvmsh(string file)
        {
            if (string.IsNullOrEmpty(file)) return null;
            if (!file.EndsWith(".xnvmsh", StringComparison.OrdinalIgnoreCase)) file += ".xnvmsh";
            if (_xnv.TryGetValue(file, out var res)) return res;
            try
            {
                var entry = Fs.GetByName(file);
                res = entry != null ? Xnvmsh.Read(entry.Read(), file) : null;
            }
            catch (Exception ex)
            {
                Debug.LogWarning($"G3CollisionBuilder: {file}: {ex.Message}");
                res = null;
            }
            if (res != null && (res.Obsolete || res.Meshes.Count == 0)) res = null;
            return _xnv[file] = res;
        }

        // ------------------------------------------------------------------ build

        /// <summary>Adds colliders under <paramref name="root"/>; safe to call repeatedly (and per streamed cell).</summary>
        /// <param name="root">Region root ("G3World") or any sub-tree of it.</param>
        /// <param name="worldRoot">Transform whose local space is G3 world space ×0.01; defaults to the "G3World" ancestor or <paramref name="root"/>.</param>
        public static Stats Build(GameObject root, Transform worldRoot = null)
        {
            var st = new Stats();
            if (root == null) return st;
            if (worldRoot == null)
            {
                worldRoot = root.transform;
                for (var t = root.transform; t != null; t = t.parent)
                    if (t.name == "G3World") { worldRoot = t; break; }
            }
            Directory.CreateDirectory(Path.Combine(Application.dataPath, "..", CollisionRoot));

            // Trees first: everything below a "Trees" group is a prefab instance with renderers we must not mesh-collide.
            var treeRoots = new HashSet<Transform>();
            foreach (var t in root.GetComponentsInChildren<Transform>(true))
                if (t.parent != null && t.parent.name == "Trees") treeRoots.Add(t);

            foreach (var tree in treeRoots)
            {
                if (HasCollision(tree.gameObject)) { st.AlreadyDone++; continue; }
                if (AddTreeCollider(tree, worldRoot)) { st.Trees++; st.Colliders++; }
            }

            foreach (var mf in root.GetComponentsInChildren<MeshFilter>(true))
            {
                var go = mf.gameObject;
                if (mf.sharedMesh == null || InTree(go.transform, treeRoots) || go.GetComponent<MeshRenderer>() == null) continue;
                if (go.GetComponentInParent<G3.Unity.Characters.G3Character>(true) != null) continue; // NPC gear: not world collision
                st.Objects++;
                if (HasCollision(go)) { st.AlreadyDone++; continue; }
                try { BuildObject(go, mf, worldRoot, st); }
                catch (Exception ex) { Debug.LogWarning($"G3CollisionBuilder: {go.name}: {ex.Message}"); st.Skipped++; }
            }
            st.MeshAssetsCreated = _created;
            _created = 0;
            return st;
        }

        static int _created;

        static bool InTree(Transform t, HashSet<Transform> trees)
        {
            for (; t != null; t = t.parent) if (trees.Contains(t)) return true;
            return false;
        }

        static bool HasCollision(GameObject go) => go.GetComponent<Collider>() != null || go.transform.Find(ChildName) != null;

        static void BuildObject(GameObject go, MeshFilter mf, Transform worldRoot, Stats st)
        {
            var mr = go.GetComponent<MeshRenderer>();
            if (IsWater(mr)) { st.Skipped++; return; }
            string meshName = mf.sharedMesh.name;
            if (meshName.EndsWith(".xcmsh", StringComparison.OrdinalIgnoreCase)) meshName = Stem(meshName);
            var posCm = worldRoot.InverseTransformPoint(go.transform.position) / S;
            var rec = FindEntity(posCm, go.name, meshName);

            if (rec == null) { st.Unmatched++; Heuristic(go, mf, mr, st); return; }
            if (rec.IsWater) { st.Skipped++; return; }
            if (rec.Shapes == null) { st.NoCollisionInGame++; return; }

            if (rec.Shapes.Count == 0)
            {
                // Lazily generated by the engine from the visual mesh.
                var res = LoadXnvmsh(meshName) ?? LoadXnvmsh(Stem(rec.Resource));
                if (res != null)
                {
                    var key = Path.GetFileNameWithoutExtension(res.Name);
                    var m = GetCollisionMesh(key, res, -1, out bool convex);
                    if (m != null)
                    {
                        Surface(AddMeshCollider(go, m, convex), DominantMaterial(res));
                        st.FromLazyXnvmsh++; st.Colliders++; return;
                    }
                }
                AddMeshCollider(go, RenderCollisionMesh(mf.sharedMesh), false);
                st.FromRender++; st.Colliders++;
                return;
            }

            int added = 0; bool anyMesh = false;
            foreach (var cs in rec.Shapes)
            {
                if (!Relevant(cs)) continue;
                var before = new HashSet<Collider>(go.GetComponentsInChildren<Collider>(true));
                int shapeMaterial = cs.Material;
                switch (cs.Type)
                {
                    case CollisionShapeType.TriMesh:
                    case CollisionShapeType.ConvexHull:
                    {
                        var res = LoadXnvmsh(cs.File);
                        if (res != null && cs.ResourceIndex >= 0 && cs.ResourceIndex < res.Meshes.Count && res.Meshes[cs.ResourceIndex].ShapeMaterial > 0)
                            shapeMaterial = res.Meshes[cs.ResourceIndex].ShapeMaterial;
                        if (res == null) break;
                        var m = GetCollisionMesh(Path.GetFileNameWithoutExtension(res.Name), res, cs.ResourceIndex, out bool convex);
                        if (m == null) break;
                        convex |= cs.Type == CollisionShapeType.ConvexHull;
                        // "<mesh>_SCX_0_8000_SCY_..." / "<mesh>_SC_1_2960" files are cooked pre-scaled: cancel the object's own scale.
                        bool prescaled = CollisionRules.IsPrescaled(res.Name);
                        if (prescaled && (go.transform.localScale - Vector3.one).sqrMagnitude > 1e-6f)
                        {
                            var c = Child(go.transform);
                            var s = go.transform.localScale;
                            c.localScale = new Vector3(1 / s.x, 1 / s.y, 1 / s.z);
                            AddMeshCollider(c.gameObject, m, convex);
                        }
                        else AddMeshCollider(go, m, convex);
                        added++; anyMesh = true;
                        break;
                    }
                    case CollisionShapeType.Box:
                    case CollisionShapeType.Sphere:
                    case CollisionShapeType.Capsule:
                        if (AddPrimitive(go, cs)) added++;
                        break;
                }
                foreach (var c in go.GetComponentsInChildren<Collider>(true))
                    if (!before.Contains(c)) Surface(c, shapeMaterial);
            }
            st.Colliders += added;
            if (added == 0) { st.NoCollisionInGame++; return; }
            if (anyMesh) st.FromXnvmsh++; else st.Primitives++;
        }

        /// <summary>Player-relevant shape groups only (static world, dynamic props, trunks, doors).</summary>
        static bool Relevant(CollisionShape cs) => CollisionRules.BlocksPlayer(cs);

        static void Heuristic(GameObject go, MeshFilter mf, MeshRenderer mr, Stats st)
        {
            var mesh = mf.sharedMesh;
            var size = Vector3.Scale(mesh.bounds.size, go.transform.lossyScale);
            bool terrain = go.name.IndexOf("Landscape", StringComparison.OrdinalIgnoreCase) >= 0 ||
                           mesh.name.IndexOf("Landscape", StringComparison.OrdinalIgnoreCase) >= 0;
            if (!terrain && (IsFoliage(mr) || Mathf.Max(size.x, size.y, size.z) < 0.4f || IsDecal(go, size)))
            {
                st.Skipped++;
                return;
            }
            if (terrain || Mathf.Max(size.x, size.y, size.z) > 3f)
            {
                AddMeshCollider(go, terrain ? mesh : RenderCollisionMesh(mesh), false);
                st.FromRender++;
            }
            else
            {
                var box = go.AddComponent<BoxCollider>();
                box.center = mesh.bounds.center;
                box.size = mesh.bounds.size;
                st.Primitives++;
            }
            st.Colliders++;
        }

        /// <summary>Water surface mesh: every drawn material is water (<see cref="CollisionRules.IsWaterSurface"/>).</summary>
        static bool IsWater(Renderer r) =>
            CollisionRules.IsWaterSurface(r.sharedMaterials.Where(m => m != null).Select(m => (m.name, m.shader != null ? m.shader.name : null)));

        /// <summary>All visible materials alpha-clipped or transparent (leaves, grass cards, nets).</summary>
        static bool IsFoliage(Renderer r)
        {
            int visible = 0, clipped = 0;
            foreach (var m in r.sharedMaterials)
            {
                if (m == null) continue;
                visible++;
                bool clip = m.renderQueue >= 2450 || m.IsKeywordEnabled("_ALPHATEST_ON") ||
                            (m.HasProperty("_AlphaClip") && m.GetFloat("_AlphaClip") > 0.5f) ||
                            m.shader != null && (m.shader.name.IndexOf("Vegetation", StringComparison.OrdinalIgnoreCase) >= 0 ||
                                                 m.shader.name.IndexOf("Foliage", StringComparison.OrdinalIgnoreCase) >= 0);
                if (clip) clipped++;
            }
            return visible > 0 && clipped == visible;
        }

        static bool IsDecal(GameObject go, Vector3 size)
        {
            float min = Mathf.Min(size.x, size.y, size.z), max = Mathf.Max(size.x, size.y, size.z);
            return go.name.IndexOf("decal", StringComparison.OrdinalIgnoreCase) >= 0 || (min < 0.02f && max < 4f);
        }

        // ------------------------------------------------------------------ colliders

        static Transform Child(Transform parent)
        {
            var c = new GameObject(ChildName).transform;
            c.SetParent(parent, false);
            c.gameObject.isStatic = parent.gameObject.isStatic;
            return c;
        }

        static MeshCollider AddMeshCollider(GameObject go, Mesh mesh, bool convex)
        {
            var mc = go.AddComponent<MeshCollider>();
            // Two-sided meshes (name suffix TwoSidedSuffix) must not be cleaned or welded: PhysX may drop a reversed copy as a
            // duplicate triangle. They are cleaned of degenerate triangles when built.
            bool twoSided = mesh != null && mesh.name.EndsWith(TwoSidedSuffix, StringComparison.Ordinal);
            mc.cookingOptions = twoSided
                ? MeshColliderCookingOptions.CookForFasterSimulation | MeshColliderCookingOptions.UseFastMidphase
                : MeshColliderCookingOptions.CookForFasterSimulation | MeshColliderCookingOptions.EnableMeshCleaning |
                  MeshColliderCookingOptions.WeldColocatedVertices | MeshColliderCookingOptions.UseFastMidphase;
            mc.convex = convex;
            mc.sharedMesh = mesh;
            return mc;
        }

        // ---- footstep surface: G3's eEShapeMaterial kept as a shared PhysicsMaterial "G3Surface_<n>_<Name>" (SurfaceProbe reads it)

        public const string SurfaceRoot = G3AssetCache.Root + "/Collision/Surfaces";
        static readonly Dictionary<int, PhysicsMaterial> _surfaces = new Dictionary<int, PhysicsMaterial>();

        static void Surface(Collider c, int shapeMaterial)
        {
            if (c == null || shapeMaterial <= 0) return;
            var m = SurfaceMaterial(shapeMaterial);
            if (m != null) c.sharedMaterial = m;
        }

        /// <summary>The most common non-zero ShapeMaterial of the collidable sub-meshes (0 = none).</summary>
        static int DominantMaterial(CollisionMeshResource res)
        {
            var counts = new Dictionary<int, int>();
            int best = 0, bestN = 0;
            foreach (var m in res.Meshes)
            {
                if (m.DisableCollision || m.ShapeMaterial == 0) continue;
                counts.TryGetValue(m.ShapeMaterial, out int n);
                counts[m.ShapeMaterial] = ++n;
                if (n > bestN) { best = m.ShapeMaterial; bestN = n; }
            }
            return best;
        }

        static PhysicsMaterial SurfaceMaterial(int shapeMaterial)
        {
            if (_surfaces.TryGetValue(shapeMaterial, out var m) && m != null) return m;
            string name = G3.Unity.SurfaceProbe.SurfaceMaterialName(shapeMaterial, TemplateShapes.MaterialName(shapeMaterial));
            string path = $"{SurfaceRoot}/{name}.asset";
            m = AssetDatabase.LoadAssetAtPath<PhysicsMaterial>(path);
            if (m == null)
            {
                Directory.CreateDirectory(SurfaceRoot);
                m = new PhysicsMaterial(name);   // Unity's default friction values: only the name carries information
                AssetDatabase.CreateAsset(m, path);
            }
            _surfaces[shapeMaterial] = m;
            return m;
        }

        static Vector3 V(float[] a, int o = 0) => new Vector3(a[o], a[o + 1], a[o + 2]);

        static Quaternion Orientation(float[] axes)
        {
            var y = V(axes, 3); var z = V(axes, 6);
            if (z.sqrMagnitude < 1e-8f || y.sqrMagnitude < 1e-8f) return Quaternion.identity;
            return Quaternion.LookRotation(z.normalized, y.normalized);
        }

        static bool AddPrimitive(GameObject go, CollisionShape cs)
        {
            var center = V(cs.Center) * S;
            var rot = Orientation(cs.Axes);
            bool rotated = Quaternion.Angle(rot, Quaternion.identity) > 0.5f;
            switch (cs.Type)
            {
                case CollisionShapeType.Box:
                {
                    var size = V(cs.Extent) * (2 * S);
                    if (size.x <= 0 || size.y <= 0 || size.z <= 0) return false;
                    if (rotated)
                    {
                        var c = Child(go.transform);
                        c.localPosition = center; c.localRotation = rot;
                        c.gameObject.AddComponent<BoxCollider>().size = size;
                    }
                    else
                    {
                        var b = go.AddComponent<BoxCollider>();
                        b.center = center; b.size = size;
                    }
                    return true;
                }
                case CollisionShapeType.Sphere:
                {
                    if (cs.Radius <= 0) return false;
                    var sc = go.AddComponent<SphereCollider>();
                    sc.center = center; sc.radius = cs.Radius * S;
                    return true;
                }
                case CollisionShapeType.Capsule:
                {
                    if (cs.Radius <= 0) return false;
                    CapsuleCollider cc;
                    if (rotated)
                    {
                        var c = Child(go.transform);
                        c.localPosition = center; c.localRotation = rot;
                        cc = c.gameObject.AddComponent<CapsuleCollider>();
                    }
                    else
                    {
                        cc = go.AddComponent<CapsuleCollider>();
                        cc.center = center;
                    }
                    cc.direction = 1;
                    cc.radius = cs.Radius * S;
                    cc.height = (cs.Height + 2 * cs.Radius) * S;
                    return true;
                }
            }
            return false;
        }

        /// <summary>
        /// Trunk capsule on a replacement tree. Uses the SpeedTree entity's Tree_Trunk capsule when it has one, otherwise
        /// a capsule sized from the tree height. Trees are uniformly scaled and yaw-only, so the collider sits on the root.
        /// </summary>
        static bool AddTreeCollider(Transform tree, Transform worldRoot)
        {
            float k = Mathf.Max(1e-4f, tree.lossyScale.y);
            float heightM = 0;
            foreach (var r in tree.GetComponentsInChildren<Renderer>(true))
                heightM = Mathf.Max(heightM, r.bounds.max.y - tree.position.y);
            if (heightM <= 0.5f) heightM = 8f;

            float radius = Mathf.Clamp(heightM * 0.018f, 0.15f, 0.6f);
            float height = Mathf.Min(heightM * 0.6f, 10f);
            float centerY = height * 0.5f;

            var posCm = worldRoot.InverseTransformPoint(tree.position) / S;
            var rec = FindEntity(posCm, tree.name, tree.name);
            var trunk = rec?.Shapes?.FirstOrDefault(s => s.Type == CollisionShapeType.Capsule && s.Group == 9 && !s.DisableCollision);
            if (trunk != null)
            {
                var w = rec.World;
                float es = new Vector3(w[0], w[1], w[2]).magnitude; // entity scale
                radius = trunk.Radius * S * es;
                height = (trunk.Height + 2 * trunk.Radius) * S * es;
                centerY = trunk.Center[1] * S * es;
            }
            else if (rec != null && rec.Shapes == null)
            {
                // SpeedTree entities without a collision PS still collide in G3 (the engine builds trunk shapes); keep the estimate.
            }

            var cap = tree.gameObject.AddComponent<CapsuleCollider>();
            cap.direction = 1;
            cap.radius = radius / k;
            cap.height = Mathf.Max(height, 2 * radius) / k;
            cap.center = new Vector3(0, centerY / k, 0);
            return true;
        }

        // ------------------------------------------------------------------ mesh assets

        /// <summary>Collision mesh asset for one sub-mesh (index &gt;= 0) or all enabled sub-meshes merged (index -1).</summary>
        static Mesh GetCollisionMesh(string stem, CollisionMeshResource res, int index, out bool convex)
        {
            convex = false;
            var parts = new List<CollisionSubMesh>();
            if (index >= 0)
            {
                if (index >= res.Meshes.Count) return null;
                parts.Add(res.Meshes[index]);
            }
            else parts.AddRange(res.Meshes.Where(m => !m.DisableCollision));
            if (parts.Count == 0) return null;
            convex = parts.Count == 1 && parts[0].Convex;

            string key = (index >= 0 && res.Meshes.Count > 1 ? $"{stem}_{index}" : stem) + (convex ? "" : TwoSidedSuffix);
            if (_meshes.TryGetValue(key, out var mesh) && mesh != null) return mesh;
            string path = $"{CollisionRoot}/{Safe(key)}.asset";
            mesh = AssetDatabase.LoadAssetAtPath<Mesh>(path);
            if (mesh == null)
            {
                mesh = BuildMesh(key, parts, !convex);
                AssetDatabase.CreateAsset(mesh, path);
                _created++;
            }
            return _meshes[key] = mesh;
        }

        /// <summary>Asset-name suffix of two-sided triangle meshes (also keeps old one-sided cache assets from being reused).</summary>
        const string TwoSidedSuffix = "_2s";

        /// <summary>Two-sided collision copy of a render mesh (cached as "R_&lt;mesh&gt;_2s"); the mesh itself if unreadable.</summary>
        static Mesh RenderCollisionMesh(Mesh render)
        {
            if (render == null || !render.isReadable) return render;
            string key = "R_" + render.name + TwoSidedSuffix;
            if (_meshes.TryGetValue(key, out var mesh) && mesh != null) return mesh;
            string path = $"{CollisionRoot}/{Safe(key)}.asset";
            mesh = AssetDatabase.LoadAssetAtPath<Mesh>(path);
            if (mesh == null)
            {
                var v = render.vertices;
                var flat = new float[v.Length * 3];
                for (int i = 0; i < v.Length; i++) { flat[i * 3] = v[i].x; flat[i * 3 + 1] = v[i].y; flat[i * 3 + 2] = v[i].z; }
                var tris = CollisionRules.TwoSided(flat, render.triangles);
                mesh = new Mesh { name = key };
                mesh.indexFormat = v.Length > 65535 ? UnityEngine.Rendering.IndexFormat.UInt32 : UnityEngine.Rendering.IndexFormat.UInt16;
                mesh.vertices = v;
                mesh.triangles = tris;
                mesh.RecalculateBounds();
                AssetDatabase.CreateAsset(mesh, path);
                _created++;
            }
            return _meshes[key] = mesh;
        }

        static Mesh BuildMesh(string name, List<CollisionSubMesh> parts, bool twoSided)
        {
            int nv = parts.Sum(p => p.VertexCount), ni = parts.Sum(p => p.Indices.Length);
            var pos = new Vector3[nv];
            var tris = new int[ni];
            int vb = 0, ib = 0;
            foreach (var p in parts)
            {
                for (int i = 0; i < p.VertexCount; i++)
                    pos[vb + i] = new Vector3(p.Positions[i * 3], p.Positions[i * 3 + 1], p.Positions[i * 3 + 2]) * S;
                for (int t = 0; t + 2 < p.Indices.Length; t += 3)
                {
                    tris[ib + t] = (int)p.Indices[t] + vb;
                    tris[ib + t + 1] = (int)p.Indices[t + 1] + vb;
                    tris[ib + t + 2] = (int)p.Indices[t + 2] + vb;
                }
                vb += p.VertexCount; ib += p.Indices.Length;
            }
            if (twoSided)
            {
                var flat = new float[nv * 3];
                for (int i = 0; i < nv; i++) { flat[i * 3] = pos[i].x; flat[i * 3 + 1] = pos[i].y; flat[i * 3 + 2] = pos[i].z; }
                tris = CollisionRules.TwoSided(flat, tris);
            }
            var mesh = new Mesh { name = name };
            mesh.indexFormat = nv > 65535 ? UnityEngine.Rendering.IndexFormat.UInt32 : UnityEngine.Rendering.IndexFormat.UInt16;
            mesh.vertices = pos;
            mesh.triangles = tris;
            mesh.RecalculateBounds();
            return mesh;
        }

        static string Safe(string name)
        {
            foreach (var c in Path.GetInvalidFileNameChars()) name = name.Replace(c, '_');
            return name;
        }

        /// <summary>Removes every collider this builder could have added under <paramref name="root"/> (for rebuilding).</summary>
        public static int Clear(GameObject root)
        {
            int n = 0;
            foreach (var t in root.GetComponentsInChildren<Transform>(true).Where(t => t.name == ChildName).ToList())
            { UnityEngine.Object.DestroyImmediate(t.gameObject); n++; }
            foreach (var c in root.GetComponentsInChildren<Collider>(true).Where(c => !(c is CharacterController)).ToList())
            { UnityEngine.Object.DestroyImmediate(c); n++; }
            return n;
        }

        /// <summary>
        /// Removes the colliders this builder adds to static world objects (G3Collision children, colliders on mesh
        /// objects and on tree roots), leaving NPCs/creatures and their gear alone.
        /// </summary>
        public static int ClearWorld(GameObject root)
        {
            int n = 0;
            foreach (var t in root.GetComponentsInChildren<Transform>(true).Where(t => t.name == ChildName).ToList())
            {
                if (t.GetComponentInParent<G3.Unity.Characters.G3Character>(true) != null) continue;
                UnityEngine.Object.DestroyImmediate(t.gameObject); n++;
            }
            foreach (var c in root.GetComponentsInChildren<Collider>(true).ToList())
            {
                if (c is CharacterController || c.GetComponentInParent<G3.Unity.Characters.G3Character>(true) != null) continue;
                bool tree = c.transform.parent != null && c.transform.parent.name == "Trees";
                if (!tree && c.GetComponent<MeshFilter>() == null) continue;
                UnityEngine.Object.DestroyImmediate(c); n++;
            }
            return n;
        }

        /// <summary>
        /// Rebuilds the colliders of the generated cell scenes in place (no world re-import): open each cell additively,
        /// <see cref="ClearWorld"/>, <see cref="Build"/>, save. <paramref name="cellFilter"/>: null for all, or a
        /// substring of the scene name ("Cell_19_19"), or several separated by ',' or ';'.
        /// </summary>
        public static string RebuildCells(string cellFilter = null)
        {
            var manifest = AssetDatabase.LoadAssetAtPath<G3WorldManifest>(G3WorldBatch.ManifestPath);
            if (manifest == null) return "no manifest at " + G3WorldBatch.ManifestPath;
            var filters = string.IsNullOrEmpty(cellFilter) ? null : cellFilter.Split(new[] { ',', ';' }, StringSplitOptions.RemoveEmptyEntries).Select(f => f.Trim()).ToArray();
            var total = new Stats();
            int cells = 0, removed = 0;
            var sw = System.Diagnostics.Stopwatch.StartNew();
            foreach (var cell in manifest.cells)
            {
                if (!cell.HasScene || !File.Exists(cell.scenePath)) continue;
                string name = Path.GetFileNameWithoutExtension(cell.scenePath);
                if (filters != null && !filters.Any(f => name.IndexOf(f, StringComparison.OrdinalIgnoreCase) >= 0)) continue;
                var open = UnityEngine.SceneManagement.SceneManager.GetSceneByPath(cell.scenePath);
                bool wasOpen = open.IsValid() && open.isLoaded;
                var scene = wasOpen ? open : UnityEditor.SceneManagement.EditorSceneManager.OpenScene(cell.scenePath, UnityEditor.SceneManagement.OpenSceneMode.Additive);
                try
                {
                    foreach (var root in scene.GetRootGameObjects())
                    {
                        removed += ClearWorld(root);
                        var st = Build(root, root.transform);
                        total.Objects += st.Objects; total.FromXnvmsh += st.FromXnvmsh; total.FromLazyXnvmsh += st.FromLazyXnvmsh;
                        total.FromRender += st.FromRender; total.Primitives += st.Primitives; total.Trees += st.Trees;
                        total.NoCollisionInGame += st.NoCollisionInGame; total.Skipped += st.Skipped; total.Unmatched += st.Unmatched;
                        total.Colliders += st.Colliders; total.MeshAssetsCreated += st.MeshAssetsCreated;
                    }
                    UnityEditor.SceneManagement.EditorSceneManager.SaveScene(scene);
                    cells++;
                }
                finally
                {
                    if (!wasOpen) UnityEditor.SceneManagement.EditorSceneManager.CloseScene(scene, true);
                }
                if (cells % 20 == 0) { AssetDatabase.SaveAssets(); EditorUtility.UnloadUnusedAssetsImmediate(true); }
            }
            AssetDatabase.SaveAssets();
            string msg = $"G3CollisionBuilder.RebuildCells: {cells} cells, {removed} old colliders removed; {total}; {sw.Elapsed.TotalSeconds:F0}s";
            Debug.Log(msg);
            return msg;
        }

        /// <summary>Batch mode: Unity.exe -batchmode -projectPath . -executeMethod G3.Unity.Editor.G3CollisionBuilder.RebuildCellsHeadless [-g3cells Cell_19_19,Cell_18_19]</summary>
        public static void RebuildCellsHeadless()
        {
            var args = Environment.GetCommandLineArgs();
            int i = Array.IndexOf(args, "-g3cells");
            int code = 0;
            try { RebuildCells(i >= 0 && i + 1 < args.Length ? args[i + 1] : null); }
            catch (Exception ex) { Debug.LogException(ex); code = 1; }
            EditorApplication.Exit(code);
        }

        [MenuItem("G3/World/Rebuild Cell Colliders", priority = 110)]
        static void MenuRebuildCells() => RebuildCells();

        [MenuItem("G3/Build Colliders (scene G3World)")]
        static void MenuBuild()
        {
            var root = GameObject.Find("G3World");
            if (root == null) { Debug.LogWarning("No G3World root in the scene"); return; }
            Debug.Log("G3CollisionBuilder: " + Build(root));
            UnityEditor.SceneManagement.EditorSceneManager.MarkSceneDirty(root.scene);
        }
